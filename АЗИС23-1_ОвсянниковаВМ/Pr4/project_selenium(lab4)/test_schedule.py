class TestSchedule:


    def test_schedule_not_empty(self, real_schedule):

        assert len(real_schedule) > 0, "Расписание пустое!"

    def test_schedule_row_count(self, real_schedule):

        assert len(real_schedule) == len(EXPECTED_SCHEDULE), (
            f"\nКоличество строк не совпадает!"
            f"\nПолучено:  {len(real_schedule)}"
            f"\nОжидалось: {len(EXPECTED_SCHEDULE)}"
        )

    def test_schedule_matches_expected(self, real_schedule):
        assert real_schedule == EXPECTED_SCHEDULE, (
            f"\n не совпадает"
            f"\n\nПолучено ({len(real_schedule)} строк):"
            f"\n{self._format(real_schedule)}"
            f"\n\n Ожидалось ({len(EXPECTED_SCHEDULE)} строк):"
            f"\n{self._format(EXPECTED_SCHEDULE)}"
        )

    def test_row_by_row_diff(self, real_schedule):
        """Построчное сравнение."""
        assert len(real_schedule) == len(EXPECTED_SCHEDULE), (
            f"Количество строк: получено {len(real_schedule)}, "
            f"ожидалось {len(EXPECTED_SCHEDULE)}"
        )
        diffs = []
        for i, (got, exp) in enumerate(
                zip(real_schedule, EXPECTED_SCHEDULE), 1):
            if got != exp:
                diffs.append(
                    f"\n  Строка {i}:"
                    f"\n    Получено:  {got}"
                    f"\n    Ожидалось: {exp}"
                )
        assert not diffs, (
            f"\n Найдены различия в {len(diffs)} строках:"
            + "".join(diffs)
        )

    def test_week_type_defined(self, week_type):
        """Тип текущей недели определён."""
        assert ("нечетн" in week_type.lower()
                or "четн" in week_type.lower()), (
            f"Не удалось определить тип недели: {week_type!r}"
        )

    @staticmethod
    def _format(schedule: list) -> str:
        lines = []
        for i, row in enumerate(schedule, 1):
            lines.append(f"  {i:2d}. {row}")
        return "\n".join(lines)